"""build_esp32.py contracts for the migration images: which boards one image serves and what it carries.

Every shipping firmware is a migration target. One image per family (the chip, and the P4 split at revision 3) carries,
per flash size and flash type, the chip's partition table for that size and a bootloader of the family sized to it.

Imports the real dicts from moondeck/build/build_esp32.py (no ESP-IDF needed).
Run: `uv run --with pytest pytest test/python -q`.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "moondeck" / "build"))

from build_esp32 import FIRMWARES, LAYOUTS, family_members, layouts_markdown, migration_family, migration_tables, table_from_fragments  # noqa: E402


def families() -> set[str]:
    return {migration_family(k) for k, v in FIRMWARES.items() if v.get("ships")}


def test_every_shipping_firmware_belongs_to_a_family_that_builds_its_image():
    assert families() == {"esp32", "esp32c3", "esp32s3", "esp32s3oflash", "esp32s31", "esp32p4", "esp32p4rev3"}
    for fw, spec in FIRMWARES.items():
        if spec.get("ships"):
            assert fw in family_members(migration_family(fw))


def test_the_p4_splits_at_revision_3_because_the_two_images_exclude_each_other():
    assert migration_family("esp32p4rev1") == "esp32p4"
    assert migration_family("esp32p4rev3") == "esp32p4rev3"


def test_the_emulator_is_no_migration_target():
    assert "qemu" not in family_members("esp32")


def test_each_flash_size_and_type_gets_the_chips_table_with_a_bootloader_sized_to_it():
    s3 = [(csv.name, fw, size) for csv, fw, size in migration_tables("esp32s3")]
    assert s3 == [("4mb_moonbase.csv", "esp32s3-qspi-lite", 4), ("8mb_moonbase.csv", "esp32s3-qspi", 8),
                  ("16mb_moonbase.csv", "esp32s3-qspi", 16)]
    # Octal flash is a family of its own: its MoonBase and migration image are built to run from octal flash.
    assert [(csv.name, fw, size) for csv, fw, size in migration_tables("esp32s3oflash")] == [("32mb_moonbase.csv", "esp32s3-opi-oflash", 32)]
    classic = [(csv.name, fw, size) for csv, fw, size in migration_tables("esp32")]
    assert classic == [("4mb_moonbase.csv", "esp32-lite", 4), ("8mb_moonbase.csv", "esp32", 8),
                       ("16mb_moonbase.csv", "esp32", 16)]


def test_a_firmware_builds_with_the_table_of_its_smallest_layout():
    # The flash size the app sees comes from the bootloader header, so one app serves every layout it lists.
    for fw, spec in FIRMWARES.items():
        assert table_from_fragments(spec["fragments"]).name == Path(LAYOUTS[spec["chip"]][min(spec["layouts"])]).name, fw


def test_every_layout_a_firmware_lists_has_a_table_for_its_chip():
    for fw, spec in FIRMWARES.items():
        for size in spec["layouts"]:
            assert size in LAYOUTS[spec["chip"]], (fw, size)


def test_every_family_carries_at_least_one_table():
    for family in families():
        assert migration_tables(family), family


def test_the_build_system_page_carries_the_partition_sizes_the_tables_hold():
    # Generated by layouts_markdown(): a table or a firmware's layouts changes, and this says the page is behind.
    page = (ROOT / "docs" / "reference" / "build-system.md").read_text(encoding="utf-8")
    begin, end = page.index("<!-- layouts:begin"), page.index("<!-- layouts:end -->")
    assert page[begin:end].split("-->", 1)[1].strip() == layouts_markdown()
