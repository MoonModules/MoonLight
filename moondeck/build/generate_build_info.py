#!/usr/bin/env python3
"""Generate src/core/util/build_id.h, the git hash and library.json's version.

Only build_info.cpp includes it: what each constant means, and why the identity lives in that
one unit, is the lead of build_info.h.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT_FILE = ROOT / "src" / "core" / "util" / "build_id.h"
# Touched on every build: build_info.cpp depends on it, so the one unit holding the clock recompiles each time.
DATE_STAMP = ROOT / "src" / "core" / "util" / "build_date.stamp"

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compute_version  # noqa: E402  (the one place a version string is derived)

version = compute_version.compute("local")   # a local build's version, which the release pipeline overrides


def build_id() -> str:
    """The short git hash the binary was built from, with `+` if the tree was dirty.

    This is the answer to "which code is on this board?", which a build date cannot give: a
    date names a compile moment, the hash names the source. Regenerated on every build (the
    CMake rule is always out of date by design), so it tracks the source.

    Falls back to "nogit" for a tarball or no-git build, so it never fails the build.
    """
    def git(*args: str) -> str:
        return subprocess.run(("git", "-C", str(ROOT), *args),
                              capture_output=True, text=True, check=True).stdout.strip()
    try:
        h = git("rev-parse", "--short=8", "HEAD")
        dirty = "+" if git("status", "--porcelain") else ""
        return f"{h}{dirty}"
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return "nogit"


content = f'''#pragma once
// Generated by moondeck/build/generate_build_info.py on every build, for build_info.cpp alone.
#define MM_BUILD_ID        "{build_id()}"
#define MM_LIBRARY_VERSION "{version}"
'''

# UTF-8 on both sides: Python's default on Windows is cp1252.
# Written only when run, so build_esp32 imports build_id() for MoonBase's version without regenerating the header.
if __name__ == "__main__":
    if not (OUT_FILE.exists() and OUT_FILE.read_text(encoding="utf-8") == content):   # unchanged: no rebuild
        OUT_FILE.write_text(content, encoding="utf-8")
        print(f"Generated build_id.h: version={version}")
    DATE_STAMP.touch()
