"""Keep a build dir's generated sdkconfig in step with the fragments it was seeded from.

IDF seeds sdkconfig from SDKCONFIG_DEFAULTS only when the file is absent, so a value changed
inside a fragment never reaches an existing build dir. Each build dir records a digest of its
fragments, names and contents in their merge order; when they differ, the sdkconfig is deleted
and regenerated by `idf.py reconfigure`, which keeps the build incremental where a wiped dir
would rebuild everything. A value set in menuconfig goes too, since the fragments are the one
source of the config.
"""

import hashlib
import subprocess
import sys
from pathlib import Path

# The record of what a build dir's sdkconfig was generated from, beside it.
RECORD = "sdkconfig.fragments.sha256"


def digest(paths: list[Path]) -> str:
    """The SHA-256 of the fragments, names and contents in their merge order, since the last one setting an option wins."""
    h = hashlib.sha256()
    for path in paths:
        h.update(path.name.encode() + b"\0")
        h.update((path.read_bytes() if path.exists() else b"") + b"\0")
    return h.hexdigest()


def changed(build_dir: Path, value: str) -> bool:
    """Whether the fragments differ from the ones `build_dir`'s sdkconfig was generated from; a dir with no record counts as changed, since nothing says what seeded it."""
    record = build_dir / RECORD
    return not record.exists() or record.read_text(encoding="utf-8").strip() != value


def refresh(idf: list[str], build_dir: Path, paths: list[Path], cwd: Path, env: dict) -> str:
    """Regenerate `build_dir`'s sdkconfig when its fragments changed, `idf` being the idf.py command with its build-dir arguments; answers the digest to record once the build succeeded."""
    value = digest(paths)
    if build_dir.exists() and changed(build_dir, value):
        print(f"The sdkconfig fragments changed since {build_dir.name} was configured; regenerating its sdkconfig from them.")
        (build_dir / "sdkconfig").unlink(missing_ok=True)
        r = subprocess.run(idf + ["reconfigure"], cwd=cwd, env=env)
        if r.returncode != 0:
            sys.exit(r.returncode)
    return value


def record(build_dir: Path, value: str) -> None:
    """Note what the sdkconfig was generated from, once the build succeeded, so an interrupted configure is regenerated next time."""
    (build_dir / RECORD).write_text(value + "\n", encoding="utf-8")
